CREATE TABLE IF NOT EXISTS external_notice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code VARCHAR(100) NOT NULL,
    external_id VARCHAR(500) NOT NULL,
    source_notice_id VARCHAR(255) NOT NULL,
    title VARCHAR(2000) NOT NULL,
    published_date DATE,
    detail_url VARCHAR(4000),
    body CLOB,
    pia_related BOOLEAN NOT NULL,
    matched_keywords CLOB NOT NULL,
    classification_reason VARCHAR(4000) NOT NULL,
    fingerprint CHAR(64) NOT NULL,
    first_seen_at TIMESTAMP NOT NULL,
    last_seen_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_external_notice_external_id UNIQUE (external_id)
);

CREATE TABLE IF NOT EXISTS external_notice_attachment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_notice_id BIGINT NOT NULL,
    attachment_order INTEGER NOT NULL,
    file_name VARCHAR(2000),
    file_url VARCHAR(4000),
    CONSTRAINT fk_external_notice_attachment_notice
        FOREIGN KEY (external_notice_id) REFERENCES external_notice (id) ON DELETE CASCADE,
    CONSTRAINT uk_external_notice_attachment_order
        UNIQUE (external_notice_id, attachment_order)
);
