CREATE TABLE bid_source_collection_cursor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code VARCHAR(50) NOT NULL,
    scope VARCHAR(100) NOT NULL,
    operation VARCHAR(100) NOT NULL,
    window_start DATE NOT NULL,
    window_end DATE NOT NULL,
    next_page INTEGER NOT NULL,
    page_size INTEGER NOT NULL,
    total_count_snapshot INTEGER,
    status VARCHAR(20) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_bid_source_collection_cursor UNIQUE (
        source_code, scope, operation, window_start, window_end
    ),
    CONSTRAINT ck_bid_source_collection_cursor_range CHECK (window_end >= window_start),
    CONSTRAINT ck_bid_source_collection_cursor_page CHECK (next_page > 0 AND page_size > 0),
    CONSTRAINT ck_bid_source_collection_cursor_total CHECK (
        total_count_snapshot IS NULL OR total_count_snapshot >= 0
    ),
    CONSTRAINT ck_bid_source_collection_cursor_status CHECK (
        status IN ('PENDING', 'PARTIAL', 'COMPLETE')
    ),
    CONSTRAINT ck_bid_source_collection_cursor_version CHECK (version >= 0),
    CONSTRAINT ck_bid_source_collection_cursor_time CHECK (updated_at >= created_at)
);

CREATE INDEX ix_bid_source_collection_cursor_pending
    ON bid_source_collection_cursor (source_code, scope, status, window_end DESC);
