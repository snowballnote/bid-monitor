CREATE TABLE bid_collection_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code VARCHAR(50) NOT NULL,
    trigger_type VARCHAR(20) NOT NULL,
    query_start_date DATE NOT NULL,
    query_end_date DATE NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE,
    status VARCHAR(20) NOT NULL,
    api_call_count INTEGER,
    collected_count INTEGER NOT NULL DEFAULT 0,
    new_count INTEGER NOT NULL DEFAULT 0,
    changed_count INTEGER NOT NULL DEFAULT 0,
    failure_count INTEGER NOT NULL DEFAULT 0,
    error_code VARCHAR(100),
    CONSTRAINT ck_bid_collection_run_trigger
        CHECK (trigger_type IN ('AUTOMATIC', 'MANUAL', 'SCHEDULED')),
    CONSTRAINT ck_bid_collection_run_status
        CHECK (status IN ('RUNNING', 'SUCCESS', 'PARTIAL', 'FAILED')),
    CONSTRAINT ck_bid_collection_run_query_range CHECK (query_end_date >= query_start_date),
    CONSTRAINT ck_bid_collection_run_time_order
        CHECK (finished_at IS NULL OR finished_at >= started_at),
    CONSTRAINT ck_bid_collection_run_counts
        CHECK ((api_call_count IS NULL OR api_call_count >= 0)
            AND collected_count >= 0 AND new_count >= 0
            AND changed_count >= 0 AND failure_count >= 0)
);
CREATE INDEX ix_bid_collection_run_source_started
    ON bid_collection_run (source_code, started_at);

CREATE TABLE bid_collection_lock (
    source_code VARCHAR(50) NOT NULL,
    query_start_date DATE NOT NULL,
    query_end_date DATE NOT NULL,
    owner_token VARCHAR(36) NOT NULL,
    acquired_at TIMESTAMP WITH TIME ZONE NOT NULL,
    lease_expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    run_id BIGINT,
    CONSTRAINT pk_bid_collection_lock
        PRIMARY KEY (source_code, query_start_date, query_end_date),
    CONSTRAINT uk_bid_collection_lock_owner UNIQUE (owner_token),
    CONSTRAINT uk_bid_collection_lock_run UNIQUE (run_id),
    CONSTRAINT fk_bid_collection_lock_run FOREIGN KEY (run_id) REFERENCES bid_collection_run (id),
    CONSTRAINT ck_bid_collection_lock_range CHECK (query_end_date >= query_start_date),
    CONSTRAINT ck_bid_collection_lock_lease CHECK (lease_expires_at > acquired_at)
);

