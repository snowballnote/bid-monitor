CREATE TABLE bid_source_registration (
    source_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name VARCHAR(200) NOT NULL,
    site_url VARCHAR(2048) NOT NULL,
    site_url_sha256 BYTEA GENERATED ALWAYS AS (digest(site_url, 'sha256')) STORED,
    source_code VARCHAR(100),
    registration_status VARCHAR(30) NOT NULL,
    collection_method VARCHAR(30) NOT NULL,
    execution_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    check_status VARCHAR(20) NOT NULL DEFAULT 'NOT_CHECKED',
    detected_collection_method VARCHAR(30) NOT NULL DEFAULT 'UNDETERMINED',
    http_status INTEGER,
    content_type VARCHAR(255),
    check_attempt_id VARCHAR(36),
    check_started_at TIMESTAMP WITH TIME ZONE,
    checked_at TIMESTAMP WITH TIME ZONE,
    safe_failure_code VARCHAR(50),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_bid_source_registration_url_hash UNIQUE (site_url_sha256),
    CONSTRAINT ck_bid_source_registration_status
        CHECK (registration_status IN ('PENDING_REVIEW', 'UNDER_REVIEW', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_bid_source_registration_method
        CHECK (collection_method IN ('UNDETERMINED', 'OFFICIAL_API', 'PUBLIC_PAGE', 'RSS')),
    CONSTRAINT ck_bid_source_registration_execution CHECK (
        execution_enabled = FALSE OR (
            registration_status = 'APPROVED'
            AND source_code IS NOT NULL
            AND collection_method <> 'UNDETERMINED'
        )
    ),
    CONSTRAINT ck_bid_source_registration_time CHECK (updated_at >= created_at),
    CONSTRAINT ck_bid_source_registration_check_status
        CHECK (check_status IN ('NOT_CHECKED', 'CHECKING', 'REACHABLE', 'UNREACHABLE', 'BLOCKED')),
    CONSTRAINT ck_bid_source_registration_detected_method
        CHECK (detected_collection_method IN ('UNDETERMINED', 'OFFICIAL_API', 'PUBLIC_PAGE', 'RSS')),
    CONSTRAINT ck_bid_source_registration_http_status
        CHECK (http_status IS NULL OR (http_status >= 100 AND http_status <= 599)),
    CONSTRAINT ck_bid_source_registration_binding
        CHECK (source_code IS NULL OR registration_status = 'APPROVED'),
    CONSTRAINT ck_bid_source_registration_check_time CHECK (
        (check_status = 'NOT_CHECKED' AND check_attempt_id IS NULL
            AND check_started_at IS NULL AND checked_at IS NULL)
        OR (check_status = 'CHECKING' AND check_attempt_id IS NOT NULL
            AND check_started_at IS NOT NULL AND checked_at IS NULL)
        OR (check_status IN ('REACHABLE', 'UNREACHABLE', 'BLOCKED')
            AND check_attempt_id IS NULL AND check_started_at IS NULL AND checked_at IS NOT NULL)
    ),
    CONSTRAINT ck_bid_source_registration_check_failure CHECK (
        (check_status = 'REACHABLE' AND safe_failure_code IS NULL)
        OR (check_status IN ('UNREACHABLE', 'BLOCKED') AND safe_failure_code IS NOT NULL)
        OR (check_status = 'NOT_CHECKED' AND safe_failure_code IS NULL)
        OR (check_status = 'CHECKING'
            AND (safe_failure_code IS NULL OR safe_failure_code = 'CHECK_TIMEOUT'))
    ),
    CONSTRAINT ck_bid_source_registration_approved_method
        CHECK (registration_status <> 'APPROVED' OR collection_method <> 'UNDETERMINED')
);
CREATE UNIQUE INDEX uk_bid_source_registration_source_code
