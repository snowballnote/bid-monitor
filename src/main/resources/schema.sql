CREATE TABLE IF NOT EXISTS external_notice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code VARCHAR(100) NOT NULL,
    external_id VARCHAR(500) NOT NULL,
    source_notice_id VARCHAR(255) NOT NULL,
    title VARCHAR(2000) NOT NULL,
    published_date DATE,
    detail_url VARCHAR(4000),
    body CLOB,
    pia_related BOOLEAN NOT NULL,
    matched_keywords CLOB NOT NULL,
    classification_reason VARCHAR(4000) NOT NULL,
    fingerprint CHAR(64) NOT NULL,
    first_seen_at TIMESTAMP NOT NULL,
    last_seen_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_external_notice_external_id UNIQUE (external_id)
);

CREATE TABLE IF NOT EXISTS external_notice_attachment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_notice_id BIGINT NOT NULL,
    attachment_order INTEGER NOT NULL,
    file_name VARCHAR(2000),
    file_url VARCHAR(4000),
    CONSTRAINT fk_external_notice_attachment_notice
        FOREIGN KEY (external_notice_id) REFERENCES external_notice (id) ON DELETE CASCADE,
    CONSTRAINT uk_external_notice_attachment_order
        UNIQUE (external_notice_id, attachment_order)
);

CREATE TABLE IF NOT EXISTS notification_baseline (
    channel VARCHAR(50) NOT NULL,
    notification_type VARCHAR(100) NOT NULL,
    source_code VARCHAR(100) NOT NULL,
    completed_at TIMESTAMP NOT NULL,
    CONSTRAINT pk_notification_baseline
        PRIMARY KEY (channel, notification_type, source_code)
);

CREATE TABLE IF NOT EXISTS notification_delivery (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel VARCHAR(50) NOT NULL,
    notification_type VARCHAR(100) NOT NULL,
    source_code VARCHAR(100) NOT NULL,
    external_id VARCHAR(500) NOT NULL,
    change_type VARCHAR(20) NOT NULL,
    content_fingerprint CHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    sent_at TIMESTAMP,
    failure_reason VARCHAR(4000),
    CONSTRAINT uk_notification_delivery_dedup UNIQUE (
        channel, notification_type, source_code, external_id, content_fingerprint
    ),
    CONSTRAINT ck_notification_delivery_status
        CHECK (status IN ('PENDING', 'SENT', 'FAILED'))
);

CREATE INDEX IF NOT EXISTS ix_notification_delivery_status_created
    ON notification_delivery (status, created_at);
