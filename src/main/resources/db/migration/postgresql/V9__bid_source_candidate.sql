CREATE TABLE bid_source_candidate (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code VARCHAR(50) NOT NULL,
    source_notice_id VARCHAR(500) NOT NULL,
    revision_key VARCHAR(100) NOT NULL DEFAULT '',
    discovery_operations TEXT NOT NULL,
    discovery_paths TEXT NOT NULL,
    title TEXT NOT NULL,
    list_fields TEXT NOT NULL,
    detail_fields TEXT NOT NULL,
    parsed_qualification TEXT NOT NULL,
    detail_status VARCHAR(30) NOT NULL,
    qualification_state VARCHAR(30),
    title_relevance VARCHAR(30) NOT NULL,
    promotion_state VARCHAR(30),
    decision_reason VARCHAR(100) NOT NULL,
    allowed_codes TEXT NOT NULL,
    allowed_codes_hash VARCHAR(64) NOT NULL,
    parser_version VARCHAR(100) NOT NULL,
    policy_version VARCHAR(100) NOT NULL,
    first_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_bid_source_candidate_identity UNIQUE (source_code, source_notice_id, revision_key),
    CONSTRAINT ck_bid_source_candidate_detail CHECK (detail_status IN ('PENDING', 'AVAILABLE', 'FAILED', 'ITEM_MISSING')),
    CONSTRAINT ck_bid_source_candidate_qualification CHECK (qualification_state IN ('MATCH', 'MISMATCH', 'INCOMPLETE', 'ABSENT')),
    CONSTRAINT ck_bid_source_candidate_relevance CHECK (title_relevance IN ('RELEVANT', 'UNKNOWN', 'IRRELEVANT')),
    CONSTRAINT ck_bid_source_candidate_promotion CHECK (promotion_state IN ('MAIN', 'REVIEW', 'ARCHIVED')),
    CONSTRAINT ck_bid_source_candidate_decision CHECK (
        (detail_status = 'AVAILABLE' AND qualification_state IS NOT NULL AND promotion_state IS NOT NULL)
        OR (detail_status <> 'AVAILABLE' AND qualification_state IS NULL AND promotion_state IS NULL)
    ),
    CONSTRAINT ck_bid_source_candidate_time CHECK (updated_at >= first_seen_at)
);

CREATE INDEX ix_bid_source_candidate_promotion ON bid_source_candidate (source_code, promotion_state, updated_at);
