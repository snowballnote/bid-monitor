CREATE TABLE bid_source_collection_retry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code VARCHAR(50) NOT NULL,
    scope VARCHAR(100) NOT NULL,
    operation VARCHAR(100) NOT NULL,
    window_start DATE NOT NULL,
    window_end DATE NOT NULL,
    page_number INTEGER NOT NULL,
    source_notice_id VARCHAR(500) NOT NULL,
    revision VARCHAR(100) NOT NULL DEFAULT '',
    payload TEXT NOT NULL,
    retry_count INTEGER NOT NULL DEFAULT 0,
    last_error_code VARCHAR(100),
    last_attempt_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_bid_source_collection_retry UNIQUE (
        source_code, scope, operation, window_start, window_end, source_notice_id, revision
    ),
    CONSTRAINT ck_bid_source_collection_retry_range CHECK (window_end >= window_start),
    CONSTRAINT ck_bid_source_collection_retry_page CHECK (page_number > 0),
    CONSTRAINT ck_bid_source_collection_retry_count CHECK (retry_count >= 0),
    CONSTRAINT ck_bid_source_collection_retry_time CHECK (updated_at >= created_at)
);

CREATE INDEX ix_bid_source_collection_retry_pending
    ON bid_source_collection_retry (source_code, scope, created_at);
